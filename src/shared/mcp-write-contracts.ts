import type { ApiResult, ToolPrepareResult } from "./contracts";
import type { EnvironmentScope } from "./environment-contracts";
export type McpScopedTool = { serverId: string; serverName: string; serverVersion: number; name: string; description: string;
  inputSchema: Record<string, unknown>; schemaDigest: string; readOnlyClaim: boolean; uiResourceUri: string | null; visibility: ("model" | "app")[] };
export type McpToolGrant = EnvironmentScope & { id: string; serverId: string; serverVersion: number; toolName: string; schemaDigest: string;
  version: number; createdAt: string; revokedAt: string | null };
export type McpWriteReview = { kind: "mcp-write"; intentId: string; expectedIntentVersion: number; serverId: string; serverName: string;
  serverVersion: number; transport: "stdio" | "streamable-http"; accountNotice: string; toolName: string; schemaDigest: string;
  grantId: string; grantVersion: number; arguments: Record<string, unknown>; argumentsDigest: string; targetPreview: string };
export type McpWriteIntent = EnvironmentScope & { id: string; state: "prepared" | "dispatching" | "confirmed" | "rejected" | "unknown";
  version: number; review: McpWriteReview; result: unknown | null; resultDigest: string | null; errorCode: string | null; createdAt: string; updatedAt: string };
export type McpToolGrantInput = EnvironmentScope & { serverId: string; expectedServerVersion: number; toolName: string; schemaDigest: string; expectedVersion?: number };
export type McpWritePrepareInput = EnvironmentScope & { grantId: string; expectedGrantVersion: number; arguments: Record<string, unknown>; targetPreview: string; clientNonce: string };
export type McpWriteIdInput = EnvironmentScope & { id: string; expectedVersion: number };
export type McpAppView = EnvironmentScope & { id: string; intentId: string; serverId: string; serverVersion: number; resourceUri: string; epoch: number;
  proxyUrl: string; title: string; permissionsNotice: string };
export type McpWriteApi = {
  toolCatalog(input: EnvironmentScope & { serverId: string; expectedServerVersion: number }): Promise<ApiResult<McpScopedTool[]>>;
  toolGrants(input: EnvironmentScope): Promise<ApiResult<McpToolGrant[]>>;
  grantTool(input: McpToolGrantInput): Promise<ApiResult<McpToolGrant>>;
  revokeTool(input: McpWriteIdInput): Promise<ApiResult<McpToolGrant>>;
  prepareTool(input: McpWritePrepareInput): Promise<ApiResult<McpWriteIntent>>;
  toolResult(input: McpWriteIdInput): Promise<ApiResult<McpWriteIntent>>;
  listToolIntents(input: EnvironmentScope): Promise<ApiResult<McpWriteIntent[]>>;
  cancelTool(input: McpWriteIdInput): Promise<ApiResult<McpWriteIntent>>;
  requestToolApproval(input: McpWriteIdInput): Promise<ApiResult<ToolPrepareResult>>;
  openApp(input: McpWriteIdInput): Promise<ApiResult<McpAppView>>;
  closeApp(input: EnvironmentScope & { id: string; expectedEpoch: number }): Promise<ApiResult<void>>;
};
